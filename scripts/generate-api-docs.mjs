// Writes api.md, the API reference of @klaracase/sdk, from the JSDoc of the source.
// typedoc fails the run when an exported class, function, interface, type or variable has no JSDoc
// (see typedoc.json, "validation.notDocumented"), so this script is also the JSDoc coverage check.
//
//   node scripts/generate-api-docs.mjs          write api.md
//   node scripts/generate-api-docs.mjs --check  fail when api.md is not up to date
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const target = join(root, "api.md");
const check = process.argv.includes("--check");
const out = mkdtempSync(join(tmpdir(), "klaracase-api-"));

try {
  execFileSync(
    join(root, "node_modules", ".bin", "typedoc"),
    ["--options", join(root, "typedoc.json"), "--out", out],
    { cwd: root, stdio: "inherit" },
  );
  const modules = [
    ["@klaracase/sdk", "index", 'The main entry. `import { Klaracase } from "@klaracase/sdk"`.'],
    [
      "@klaracase/sdk/schemas",
      "schemas",
      'zod/mini schemas. `import * as s from "@klaracase/sdk/schemas"`.',
    ],
    [
      "@klaracase/sdk/tools",
      "tools",
      'Agent tools. `import { tools, callTool } from "@klaracase/sdk/tools"`.',
    ],
  ];
  const parts = [
    "# API reference: @klaracase/sdk\n",
    "Generated by `node scripts/generate-api-docs.mjs` from the JSDoc of the source. Do not edit by hand.\n",
    "Contents: " + modules.map(([title, file]) => `[${title}](#${file}-entry)`).join(", ") + "\n",
  ];
  for (const [title, file, summary] of modules) {
    const body = readFileSync(join(out, `${file}.md`), "utf8")
      .replace(/^# .*\n/, "")
      .replace(/^(#{2,5}) /gm, "$1# ")
      .replace(/\]\((?:index|schemas|tools)\.md#/g, "](#");
    parts.push(`\n## ${file} entry\n\n${title}. ${summary}\n${body}`);
  }
  const text = `${parts.join("\n").trimEnd()}\n`;
  if (!check) {
    writeFileSync(target, text);
    console.log(`wrote api.md (${text.split("\n").length} lines)`);
  } else if (readFileSync(target, "utf8") !== text) {
    console.error("api.md is out of date. Run: node scripts/generate-api-docs.mjs");
    process.exit(1);
  } else {
    console.log("api.md is up to date");
  }
} finally {
  rmSync(out, { recursive: true, force: true });
}
